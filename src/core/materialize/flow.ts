/**
 * Materialization (V4 MAT1, brief § 9, § 27, § 29): the Git-first flow after generation. Pure.
 *
 *   previewDiff(files, existing)          → what the branch would change, file by file
 *   materializationGitPlan(input)         → the git + host CLI arguments for branch → commit → push → MR
 *   deployHandoff(decision, candidate)    → which native tool deploys, as chosen by the Common router
 *
 * DataPass never deploys: no provider call, no apply, no publish. The Git plan is built only for an
 * explicit user action and is run by the caller through the existing Git layer; the deploy step is a
 * hand-off text naming the native tool (fabric-cicd, Fabric Git, fab, Terraform), never a command
 * DataPass runs. A file that was edited by hand after generation is "detached" (§ 28) and is never
 * overwritten silently.
 */
import type { GitHostRepo } from "../project/gitHosts";
import { isBranchName } from "../git/porcelain";
import type { ArchitectureCandidate, GeneratedFile, ValidationIssue } from "./generator";
import { sidecarPath, verifyStamp } from "./stamp";

// --- Diff preview --------------------------------------------------------------------------------

export type DiffStatus =
  | "added"
  | "modified"
  | "unchanged"
  /** The file on disk was generated but edited by hand since, or was never generated by DataPass. */
  | "blocked-detached";

export interface DiffEntry {
  path: string;
  status: DiffStatus;
  addedLines: number;
  removedLines: number;
  /** Set for blocked entries: why the file is not overwritten. */
  reason?: string;
}

/**
 * Compares the generated set with the files currently in the repository (`existing` maps a
 * repository-relative path to its content; absent = no such file). `overwriteDetached` is the explicit
 * user choice to replace hand-edited or foreign files.
 */
export function previewDiff(files: GeneratedFile[], existing: ReadonlyMap<string, string>, overwriteDetached = false): DiffEntry[] {
  const out: DiffEntry[] = [];
  for (const f of files) {
    const current = existing.get(f.path);
    if (current === undefined) {
      out.push({ path: f.path, status: "added", addedLines: lineCount(f.content), removedLines: 0 });
      continue;
    }
    if (normalize(current) === normalize(f.content)) {
      out.push({ path: f.path, status: "unchanged", addedLines: 0, removedLines: 0 });
      continue;
    }
    if (f.role === "item" && !overwriteDetached) {
      const { verdict } = verifyStamp(f.path, current, existing.get(sidecarPath(f.path)));
      if (verdict !== "intact") {
        out.push({
          path: f.path, status: "blocked-detached", addedLines: 0, removedLines: 0,
          reason: verdict === "detached"
            ? "Edited by hand after generation: the file is detached from its source. Re-attach by overwriting explicitly, or keep it."
            : "Not generated by DataPass (no provenance stamp). Overwrite only on explicit choice."
        });
        continue;
      }
    }
    const { added, removed } = lineDelta(normalize(current), normalize(f.content));
    out.push({ path: f.path, status: "modified", addedLines: added, removedLines: removed });
  }
  // A sidecar follows its item: never write a new stamp beside a file that stays blocked.
  const blocked = new Set(out.filter(e => e.status === "blocked-detached").map(e => sidecarPath(e.path)));
  for (const e of out) {
    if (blocked.has(e.path) && e.status !== "unchanged") {
      e.status = "blocked-detached";
      e.addedLines = e.removedLines = 0;
      e.reason = "Sidecar of a blocked file.";
    }
  }
  return out;
}

function normalize(s: string): string {
  return s.replace(/\r\n?/g, "\n");
}

function lineCount(s: string): number {
  const n = normalize(s);
  return n ? n.replace(/\n$/, "").split("\n").length : 0;
}

/** Added/removed line counts from a longest-common-subsequence over lines (files here are small). */
export function lineDelta(before: string, after: string): { added: number; removed: number } {
  const a = before ? before.replace(/\n$/, "").split("\n") : [];
  const b = after ? after.replace(/\n$/, "").split("\n") : [];
  if (a.length * b.length > 4_000_000) return { added: b.length, removed: a.length };
  let prev = new Array<number>(b.length + 1).fill(0);
  for (let i = 1; i <= a.length; i++) {
    const row = new Array<number>(b.length + 1).fill(0);
    for (let j = 1; j <= b.length; j++) row[j] = a[i - 1] === b[j - 1] ? prev[j - 1]! + 1 : Math.max(prev[j]!, row[j - 1]!);
    prev = row;
  }
  const common = prev[b.length]!;
  return { added: b.length - common, removed: a.length - common };
}

// --- Branch / commit / MR plan -------------------------------------------------------------------

export interface GitCommand {
  tool: "git" | "gh" | "glab" | "az";
  args: string[];
  /** One line shown to the user before the command runs. */
  label: string;
}

export interface GitPlanInput {
  /** Must be the literal "user-confirmed": the plan exists only for an explicit user action. */
  userAction: "user-confirmed";
  branch: string;
  baseBranch: string;
  candidate: ArchitectureCandidate;
  files: GeneratedFile[];
  diff: DiffEntry[];
  issues: ValidationIssue[];
  /** Host of the repository; without one the MR step is left to the user (web link from the Git view). */
  host?: GitHostRepo;
  /** Also open the merge request (a second explicit choice). */
  openMergeRequest: boolean;
}

export interface GitPlan {
  /** Files to write before the git steps (item and sidecar files that are added or modified). */
  writes: Array<{ path: string; content: string }>;
  commands: GitCommand[];
  commitMessage: string;
  /** Why the merge request step was not planned, when it was asked for. */
  mergeRequestNote?: string;
}

/** Builds the branch → commit → push (→ MR) plan, or throws when the generated set may not go to Git. */
export function materializationGitPlan(input: GitPlanInput): GitPlan {
  if (input.userAction !== "user-confirmed") throw new Error("Materialization to Git needs an explicit user action.");
  if (!isBranchName(input.branch) || !isBranchName(input.baseBranch)) throw new Error("Branch names must be plain Git branch names.");
  if (input.branch === input.baseBranch) throw new Error("Materialize on a review branch, never on the base branch.");
  const errors = input.issues.filter(i => i.severity === "error");
  if (errors.length) throw new Error(`Validation failed (${errors.length} error${errors.length > 1 ? "s" : ""}); fix the candidate first.`);

  const byPath = new Map(input.files.map(f => [f.path, f]));
  const writes = input.diff
    .filter(e => e.status === "added" || e.status === "modified")
    .map(e => ({ path: e.path, content: byPath.get(e.path)!.content }));
  if (!writes.length) throw new Error("Nothing to materialize: every generated file is unchanged or blocked.");

  const c = input.candidate;
  const commitMessage = [
    `materialize: ${c.logicalId} @ ${c.revision.slice(0, 12)} (${c.environment})`,
    "",
    `Candidate native Fabric files generated by DataPass from ${c.logicalId} at ${c.revision}.`,
    "Evidence origin: generated. Not deployed; deployment goes through the native tool after review.",
    ...input.diff.filter(e => e.status === "blocked-detached").map(e => `Kept (detached): ${e.path}`)
  ].join("\n");

  const commands: GitCommand[] = [
    { tool: "git", args: ["switch", "-c", input.branch, input.baseBranch], label: `Create branch ${input.branch} from ${input.baseBranch}` },
    { tool: "git", args: ["add", "--", ...writes.map(w => w.path)], label: `Stage ${writes.length} generated file(s)` },
    { tool: "git", args: ["commit", "-m", commitMessage], label: "Commit the candidate files" },
    { tool: "git", args: ["push", "-u", "origin", input.branch], label: `Push ${input.branch}` }
  ];

  let mergeRequestNote: string | undefined;
  if (input.openMergeRequest) {
    const mr = mergeRequestCommand(input, `Materialize ${c.logicalId} (${c.environment})`, mergeRequestBody(input));
    if (mr) commands.push(mr);
    else mergeRequestNote = "No supported host CLI for this repository: open the merge request from the Git view link.";
  }
  return { writes, commands, commitMessage, mergeRequestNote };
}

function mergeRequestBody(input: GitPlanInput): string {
  const counts = new Map<string, number>();
  for (const e of input.diff) counts.set(e.status, (counts.get(e.status) ?? 0) + 1);
  return [
    `Source: ${input.candidate.logicalId} @ ${input.candidate.revision}`,
    `Environment: ${input.candidate.environment}`,
    `Files: ${[...counts].map(([s, n]) => `${n} ${s}`).join(", ")}`,
    "",
    "Generated by DataPass (evidence origin: generated). Every file carries a provenance stamp.",
    "Nothing is deployed by this merge request; the native deployment tool runs after review."
  ].join("\n");
}

function mergeRequestCommand(input: GitPlanInput, title: string, body: string): GitCommand | undefined {
  const h = input.host;
  if (!h) return undefined;
  const label = "Open the merge request";
  if (h.kind === "github" && h.owner) {
    return { tool: "gh", args: ["pr", "create", "--repo", `${h.owner}/${h.name}`, "--head", input.branch, "--base", input.baseBranch, "--title", title, "--body", body], label };
  }
  if (h.kind === "gitlab") {
    return { tool: "glab", args: ["mr", "create", "--repo", h.web, "--source-branch", input.branch, "--target-branch", input.baseBranch, "--title", title, "--description", body, "--yes"], label };
  }
  // Azure DevOps (az.cmd through cmd.exe) cannot take a multi-line description safely: left to the web link.
  return undefined;
}

// --- Deploy hand-off (Common capability router) --------------------------------------------------

/**
 * The part of the Common `capability-router` RouteDecision this step reads (structural copy of
 * `@juliandatapass-group/capability-router` contract; swap for the import once the standalone
 * vendors the package, CAPROUTE1b).
 */
export interface RouteDecisionLike {
  operationId: string;
  preferred: { candidateId: string; reason: string } | null;
  fallback: { candidateId: string; reason: string } | null;
  candidates: Array<{ candidateId: string; providerId: string; readiness: string; routeKind: string; gaps?: unknown[] }>;
}

export const DEPLOY_OPERATIONS = ["fabric.workspace.deploy", "fabric.iac.terraform-deploy"] as const;

export interface DeployHandoff {
  operationId: string;
  candidateId?: string;
  providerId?: string;
  readiness?: string;
  /** What the user (or their pipeline) runs with the native tool. Shown, never run by DataPass. */
  instructions: string[];
  reason: string;
}

export function deployHandoff(decision: RouteDecisionLike, candidate: ArchitectureCandidate): DeployHandoff {
  if (!(DEPLOY_OPERATIONS as readonly string[]).includes(decision.operationId)) {
    throw new Error(`Operation ${decision.operationId} is not a deployment route.`);
  }
  const pick = decision.preferred ?? decision.fallback;
  const chosen = pick && decision.candidates.find(c => c.candidateId === pick.candidateId);
  if (!pick || !chosen) {
    return {
      operationId: decision.operationId,
      instructions: ["No deployment tool is ready for this project. Set one up from the capability card, then deploy from the merged branch."],
      reason: "The capability router returned no preferred or fallback candidate."
    };
  }
  return {
    operationId: decision.operationId,
    candidateId: chosen.candidateId,
    providerId: chosen.providerId,
    readiness: chosen.readiness,
    instructions: instructionsFor(chosen.candidateId, candidate),
    reason: pick.reason
  };
}

function instructionsFor(candidateId: string, c: ArchitectureCandidate): string[] {
  const after = `After the merge request is reviewed and merged, deploy ${c.rootDirectory} for environment "${c.environment}"`;
  switch (candidateId) {
    case "fabric-cicd":
    case "fabric-cicd-gbrueckl":
      return [`${after} with fabric-cicd (publish_all_items on repository_directory "${c.rootDirectory}", environment "${c.environment}").`,
        "Use the project's safe deployment config (.deploy/fabric.yml: unpublish skipped)."];
    case "fab-deploy":
      return [`${after} with the Fabric CLI (fab), following its deploy documentation.`];
    case "fabric-git":
      return [`${after} by updating the Fabric workspace connected to the merged branch (Fabric Git integration, Source control → Update).`];
    case "terraform-fabric":
      return [`${after} through the project's Terraform workflow (plan, review, apply in its own pipeline).`];
    default:
      return [`${after} with ${candidateId}, the tool chosen by the capability router.`];
  }
}
