/** Sections from `datapass.explain.sections` when valid, else the defaults (settings are data, not contracts). */
export function sectionsFromSetting(raw: unknown): readonly ExplainSection[] {
  if (!Array.isArray(raw) || !raw.length) return DEFAULT_EXPLAIN_SECTIONS;
  const ok = raw.filter((s): s is ExplainSection => !!s && typeof s === "object" && typeof s.id === "string" && typeof s.title === "string"
    && typeof s.source === "string" && Array.isArray(s.layouts) && s.layouts.every((l: unknown) => typeof l === "string"));
  return ok.length ? ok : DEFAULT_EXPLAIN_SECTIONS;
}
